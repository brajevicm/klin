class Tree:
    def __init__(self, root):
        self.root = root
        self.py = PyManifests(root)
        self.ts = TsManifests(root)
        self.local = local_modules(root)
        self.parse_errors = []
        self.sites = []
        for rel, full in walk(root):
            if rel.endswith(PY_EXT):
                text = read(full)
                found = py_sites(rel, text)
                if found is None:
                    self.parse_errors.append(rel)
                    continue
                tags = path_tags(rel, text)
                for module, line, site_tags in found:
                    if module in STDLIB or module in self.local or module == "__future__":
                        continue
                    self.sites.append(("python", module, rel, line, sorted(set(tags + site_tags))))
            elif rel.endswith(TS_EXT) and not rel.endswith(".min.js"):
                text = read(full)
                tags = path_tags(rel, text)
                for spec, line, site_tags in ts_sites(text):
                    if not self.ts.judged(spec):
                        continue
                    self.sites.append(("ts", self.ts.package(spec), rel, line, sorted(set(tags + site_tags))))

    def declared(self, lang, identity, variant):
        if lang == "python":
            return self.py.declares(identity, variant)
        return self.ts.declares(identity)

    def undeclared(self, variant):
        out = {}
        for lang, identity, rel, line, tags in self.sites:
            if lang == "python" and self.py.unknown:
                continue
            if not self.declared(lang, identity, variant):
                out.setdefault((lang, identity), []).append((rel, line, tags))
        return out


def cmd_imports(root):
    tree = Tree(root)
    for lang, identity, rel, line, tags in tree.sites:
        status = ",".join(v for v in VARIANTS if not tree.declared(lang, identity, v)) or "declared"
        print(f"{lang}\t{identity}\t{rel}:{line}\t{','.join(tags) or '-'}\t{status}")
    for item in tree.py.unknown:
        print(f"python\t-\t{item}\t-\tunknown")


def cmd_new(before_root, after_root):
    before, after = Tree(before_root), Tree(after_root)
    if after.py.unknown:
        print(f"python\t*\t-\t-\tunknown\t{'; '.join(after.py.unknown)}")
    for variant in VARIANTS:
        old = before.undeclared(variant)
        old_untagged = {key for key, sites in old.items() if any(not tags for _, _, tags in sites)}
        for key, sites in sorted(after.undeclared(variant).items()):
            lang, identity = key
            if lang == "ts" and variant != "exact":
                continue
            untagged = [s for s in sites if not s[2]]
            if key in old_untagged:
                continue
            if untagged:
                rel, line, _ = untagged[0]
                print(f"{lang}\t{variant}\t{identity}\t{rel}:{line}\tfinding\t-")
            elif key not in old:
                rel, line, tags = sites[0]
                every = sorted({t for s in sites for t in s[2]})
                print(f"{lang}\t{variant}\t{identity}\t{rel}:{line}\texcluded\t{','.join(every)}")


