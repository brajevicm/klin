def strip_comments(text):
    out = []
    i, n = 0, len(text)
    quote = None
    while i < n:
        c = text[i]
        if quote:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == quote:
                quote = None
            i += 1
            continue
        if c in "'\"`":
            quote = c
            out.append(c)
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            end = n if j < 0 else j + 2
            out.append("\n" * text.count("\n", i, end))
            i = end
        else:
            out.append(c)
            i += 1
    return "".join(out)


TS_PATTERNS = [
    re.compile(r"(?<![.\w$])import\s+(type\s+)?[\w*{}\s,$]*?\bfrom\s*(['\"])([^'\"\n]+)\2", re.S),
    re.compile(r"(?<![.\w$])export\s+(type\s+)?[\w*{}\s,$]*?\bfrom\s*(['\"])([^'\"\n]+)\2", re.S),
    re.compile(r"(?<![.\w$])import\s*()(['\"])([^'\"\n]+)\2"),
    re.compile(r"(?<![.\w$])import\s*\(\s*()(['\"])([^'\"\n]+)\2\s*\)"),
    re.compile(r"(?<![.\w$])require\s*\(\s*()(['\"])([^'\"\n]+)\2\s*\)"),
]


def ts_sites(text):
    stripped = strip_comments(text)
    seen = set()
    sites = []
    for pattern in TS_PATTERNS:
        for match in pattern.finditer(stripped):
            start = match.start(3)
            if start in seen:
                continue
            seen.add(start)
            line = stripped.count("\n", 0, start) + 1
            tags = ["type-only"] if match.group(1) else []
            sites.append((match.group(3), line, tags))
    return sorted(sites, key=lambda s: s[1])


def jsonc(text):
    text = strip_comments(text)
    text = re.sub(r",(\s*[}\]])", r"\1", text)
    return json.loads(text)


class TsManifests:
    def __init__(self, root):
        self.declared = {}
        self.direct = {}
        self.members = set()
        self.aliases = []
        self.private_scopes = set()
        self.private_all = False
        for rel, full in walk(root):
            name = rel.split("/")[-1]
            if name == "package.json":
                try:
                    data = json.loads(read(full))
                except ValueError:
                    continue
                if not isinstance(data, dict):
                    continue
                if isinstance(data.get("name"), str):
                    self.declared.setdefault(data["name"], rel)
                    self.members.add(data["name"])
                for table in ("dependencies", "devDependencies", "peerDependencies", "optionalDependencies"):
                    for dep, spec in (data.get(table) or {}).items():
                        self.declared.setdefault(dep, rel)
                        if not isinstance(spec, str):
                            continue
                        alias = re.match(r"npm:((?:@[^/@]+/)?[^@]+)", spec)
                        if alias:
                            self.direct.setdefault(alias.group(1), rel)
                        elif not re.match(r"(workspace:|file:|link:|portal:|git|github:|https?:|[\w-]+/[\w.-]+$)", spec):
                            self.direct.setdefault(dep, rel)
            elif re.fullmatch(r"(tsconfig.*|jsconfig)\.json", name):
                try:
                    data = jsonc(read(full))
                except ValueError:
                    continue
                paths = (data.get("compilerOptions") or {}).get("paths") or {}
                self.aliases.extend(paths.keys())
            elif name == ".npmrc":
                for line in read(full).splitlines():
                    match = re.match(r"\s*(@[\w.-]+:)?registry\s*=\s*(\S+)", line)
                    if match and "registry.npmjs.org" not in match.group(2) and "registry.yarnpkg.com" not in match.group(2):
                        if match.group(1):
                            self.private_scopes.add(match.group(1)[:-1])
                        else:
                            self.private_all = True

    def package(self, spec):
        parts = spec.split("/")
        return "/".join(parts[:2]) if spec.startswith("@") else parts[0]

    def judged(self, spec):
        if spec.startswith((".", "/", "#", "$", "~")) or re.match(r"^[a-zA-Z][\w+.-]*:", spec):
            return False
        if spec in NODE_BUILTINS or spec.split("/")[0] in NODE_BUILTINS:
            return False
        if any(fnmatch.fnmatchcase(spec, alias) for alias in self.aliases):
            return False
        return True

    def declares(self, package):
        if package in self.declared:
            return True
        types = "@types/" + (package[1:].replace("/", "__") if package.startswith("@") else package)
        return types in self.declared

    def is_private(self, package):
        return self.private_all or (package.startswith("@") and package.split("/")[0] in self.private_scopes)


