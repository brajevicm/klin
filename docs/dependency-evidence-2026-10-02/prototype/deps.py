NPM_INTEGRITY = re.compile(r"^(sha512-[A-Za-z0-9+/]{86}==|sha1-[A-Za-z0-9+/]{27}=)$")
CARGO_CHECKSUM = re.compile(r"^[0-9a-f]{64}$")
GO_HASH = re.compile(r"^h1:[A-Za-z0-9+/]{43}=$")


def npm_entry_problem(entry):
    resolved = entry.get("resolved")
    if resolved is None:
        return "no resolved"
    if not resolved.startswith("https://"):
        return None
    integrity = entry.get("integrity")
    if integrity is None:
        return "no integrity"
    if not any(NPM_INTEGRITY.match(token) for token in integrity.split()):
        return "malformed integrity"
    return None


def npm_v1(tree, prefix, out, rel):
    for name, entry in (tree or {}).items():
        if not isinstance(entry, dict):
            continue
        version = str(entry.get("version", ""))
        if not (entry.get("bundled") or version.startswith(("file:", "git", "link:")) or "://" in version and not version.startswith("https")):
            problem = npm_entry_problem(entry)
            if problem:
                out.append((rel, prefix + name, problem))
        npm_v1(entry.get("dependencies"), prefix + name + ">", out, rel)


def cargo_members(root):
    names = set()
    for rel, full in walk(root):
        if rel.split("/")[-1] == "Cargo.toml":
            try:
                names.add(tomllib.loads(read(full)).get("package", {}).get("name"))
            except tomllib.TOMLDecodeError:
                pass
    return names


def lockshape(root):
    members = None
    out = []
    counts = {"npm": 0, "cargo": 0, "go": 0}
    for rel, full in walk(root):
        name = rel.split("/")[-1]
        if name == "package-lock.json":
            try:
                data = json.loads(read(full))
            except ValueError:
                out.append((rel, "-", "not JSON"))
                continue
            packages = data.get("packages")
            if isinstance(packages, dict):
                for key, entry in packages.items():
                    if key == "" or "node_modules/" not in key or entry.get("link") or entry.get("inBundle"):
                        continue
                    counts["npm"] += 1
                    problem = npm_entry_problem(entry)
                    if problem:
                        out.append((rel, key, problem))
            else:
                npm_v1(data.get("dependencies"), "", out, rel)
                counts["npm"] += len(data.get("dependencies") or {})
        elif name == "Cargo.lock":
            try:
                data = tomllib.loads(read(full))
            except tomllib.TOMLDecodeError:
                out.append((rel, "-", "not TOML"))
                continue
            metadata = data.get("metadata", {}) or {}
            members = members or cargo_members(root)
            for package in data.get("package", []) or []:
                source = package.get("source")
                if (source or "").startswith("git+") or (not source and package.get("name") in members):
                    continue
                counts["cargo"] += 1
                if not source:
                    out.append((rel, f"{package.get('name')} {package.get('version')}", "no source"))
                    continue
                checksum = package.get("checksum") or metadata.get(
                    f"checksum {package.get('name')} {package.get('version')} ({source})")
                if checksum is None:
                    out.append((rel, f"{package.get('name')} {package.get('version')}", "no checksum"))
                elif not CARGO_CHECKSUM.match(checksum):
                    out.append((rel, f"{package.get('name')} {package.get('version')}", "malformed checksum"))
        elif name == "go.sum":
            for number, line in enumerate(read(full).splitlines(), 1):
                fields = line.split()
                if not fields:
                    continue
                counts["go"] += 1
                if len(fields) != 3 or not GO_HASH.match(fields[2]):
                    out.append((rel, f"line {number}", "malformed hash"))
    return out, counts


