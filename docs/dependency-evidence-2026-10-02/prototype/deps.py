IMPORT_ERRORS = {"ImportError", "ModuleNotFoundError", "Exception", "BaseException"}
PLATFORM_TEXT = ("sys.platform", "os.name", "platform.system", "sys.version_info")


def handler_names(handler):
    if handler.type is None:
        return {"Exception"}
    nodes = handler.type.elts if isinstance(handler.type, ast.Tuple) else [handler.type]
    return {n.id if isinstance(n, ast.Name) else n.attr if isinstance(n, ast.Attribute) else "" for n in nodes}


def py_sites(rel, text):
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return None
    sites = []

    def visit(node, tags):
        if isinstance(node, ast.Import):
            for alias in node.names:
                sites.append((alias.name.split(".")[0], node.lineno, sorted(tags)))
        elif isinstance(node, ast.ImportFrom):
            if node.level == 0 and node.module:
                sites.append((node.module.split(".")[0], node.lineno, sorted(tags)))
        if isinstance(node, ast.Try) or (hasattr(ast, "TryStar") and isinstance(node, ast.TryStar)):
            guarded = any(handler_names(h) & IMPORT_ERRORS for h in node.handlers)
            for child in node.body:
                visit(child, tags | ({"guarded"} if guarded else set()))
            for child in node.handlers + node.orelse + node.finalbody:
                visit(child, tags)
            return
        if isinstance(node, ast.If):
            test = ast.unparse(node.test)
            if re.fullmatch(r"(typing\.)?TYPE_CHECKING", test.strip()):
                for child in node.body:
                    visit(child, tags | {"type-only"})
                for child in node.orelse:
                    visit(child, tags)
                return
            if any(p in test for p in PLATFORM_TEXT):
                for child in node.body + node.orelse:
                    visit(child, tags | {"platform"})
                return
        for child in ast.iter_child_nodes(node):
            visit(child, tags)

    visit(tree, set())
    return sites


def local_modules(root):
    names = set()
    for rel, full in walk(root):
        parts = rel.split("/")
        stem, ext = os.path.splitext(parts[-1])
        if ext in (".py", ".pyi", ".pyx", ".so"):
            names.add(stem.split(".")[0])
            if ext == ".py" and len(parts) > 1:
                names.add(parts[-2])
    return names


