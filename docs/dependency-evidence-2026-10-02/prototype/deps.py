def new_findings(before_root, after_root):
    before, after = Tree(before_root), Tree(after_root)
    found, excluded = {}, {}
    for variant in VARIANTS:
        old = before.undeclared(variant)
        old_untagged = {key for key, sites in old.items() if any(not tags for _, _, tags in sites)}
        for key, sites in sorted(after.undeclared(variant).items()):
            if key in old_untagged or (key[0] == "ts" and variant != "exact"):
                continue
            if any(not tags for _, _, tags in sites):
                found.setdefault(key, []).append(variant)
            elif key not in old:
                excluded[key] = sorted({t for s in sites for t in s[2]})
    return found, excluded, after.py.unknown


