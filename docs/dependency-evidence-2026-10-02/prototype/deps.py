def walk(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            yield os.path.relpath(full, root).replace(os.sep, "/"), full


def read(full):
    try:
        with open(full, "rb") as handle:
            return handle.read().decode("utf-8", "replace")
    except OSError:
        return ""


def path_tags(rel, text):
    segments = rel.split("/")
    dirs, name = segments[:-1], segments[-1]
    tags = []
    if (any(d in TEST_SEGMENTS for d in dirs) or name.startswith("test_") or name.endswith("_test.py")
            or name == "conftest.py" or ".test." in name or ".spec." in name or ".stories." in name):
        tags.append("test")
    if any(d in EXAMPLE_SEGMENTS for d in dirs):
        tags.append("example")
    if any(d in VENDORED_SEGMENTS for d in dirs):
        tags.append("vendored")
    if (any(m in text[:2048].lower() for m in GENERATED_MARKERS)
            or name.endswith("_pb2.py") or name.endswith("_pb2_grpc.py")):
        tags.append("generated")
    return tags


