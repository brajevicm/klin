REQ_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def requirement_name(spec):
    spec = spec.strip()
    if not spec or spec.startswith("#"):
        return None
    if spec.startswith("-e ") or spec.startswith("--editable"):
        egg = re.search(r"#egg=([A-Za-z0-9._-]+)", spec)
        return egg.group(1) if egg else None
    if spec.startswith("-") or "://" in spec.split("@")[0]:
        return None
    match = REQ_NAME.match(spec)
    return match.group(1) if match else None


def requirement_is_registry(spec):
    return "@" not in spec.split(";")[0] and "://" not in spec


class PyManifests:
    def __init__(self, root):
        self.root = root
        self.dists = {}
        self.direct = {}
        self.unknown = []
        self.private = False
        self.read_files = set()
        self.files = {rel: full for rel, full in walk(root)}
        for rel, full in self.files.items():
            name = rel.split("/")[-1]
            parent = rel.split("/")[-2] if "/" in rel else ""
            if name == "pyproject.toml":
                self.pyproject(rel, full)
            elif re.fullmatch(r"requirements.*\.txt", name) or (parent == "requirements" and name.endswith((".txt", ".in"))):
                self.requirements(rel, full)
            elif name == "setup.cfg":
                self.setup_cfg(rel, full)
            elif name == "setup.py":
                self.setup_py(rel, full)
            elif name == "Pipfile":
                self.pipfile(rel, full)

    def add(self, name, rel, registry=True):
        if not name or name.lower() == "python":
            return
        self.dists.setdefault(norm(name), rel)
        if registry:
            self.direct.setdefault(norm(name), rel)

    def add_spec(self, spec, rel):
        name = requirement_name(spec)
        if name:
            self.add(name, rel, requirement_is_registry(spec))

    def pyproject(self, rel, full):
        try:
            data = tomllib.loads(read(full))
        except tomllib.TOMLDecodeError:
            self.unknown.append(rel + ": not TOML")
            return
        project = data.get("project", {})
        for spec in project.get("dependencies", []) or []:
            self.add_spec(spec, rel)
        for specs in (project.get("optional-dependencies", {}) or {}).values():
            for spec in specs:
                self.add_spec(spec, rel)
        for specs in (data.get("dependency-groups", {}) or {}).values():
            for spec in specs:
                if isinstance(spec, str):
                    self.add_spec(spec, rel)
        for spec in data.get("build-system", {}).get("requires", []) or []:
            self.add_spec(spec, rel)
        tool = data.get("tool", {})
        poetry = tool.get("poetry", {})
        tables = [poetry.get("dependencies", {}), poetry.get("dev-dependencies", {})]
        tables += [group.get("dependencies", {}) for group in (poetry.get("group", {}) or {}).values()]
        for table in tables:
            for name, value in (table or {}).items():
                registry = not (isinstance(value, dict) and ("path" in value or "git" in value or "url" in value))
                self.add(name, rel, registry)
        for spec in tool.get("uv", {}).get("dev-dependencies", []) or []:
            self.add_spec(spec, rel)
        for specs in (tool.get("pdm", {}).get("dev-dependencies", {}) or {}).values():
            for spec in specs:
                self.add_spec(spec, rel)
        if "dependencies" in (project.get("dynamic", []) or []):
            dynamic = tool.get("setuptools", {}).get("dynamic", {}).get("dependencies", {})
            files = dynamic.get("file", []) if isinstance(dynamic, dict) else []
            files = [files] if isinstance(files, str) else files
            base = os.path.dirname(rel)
            readable = files and all(re.fullmatch(r"requirements.*\.txt", os.path.basename(f)) for f in files)
            if not readable:
                self.unknown.append(rel + ": dynamic dependencies")
            for f in files:
                self.requirements(os.path.normpath(os.path.join(base, f)), os.path.join(self.root, base, f))
        if tool.get("uv", {}).get("index") or tool.get("poetry", {}).get("source") or tool.get("pdm", {}).get("source"):
            self.private = True

    def requirements(self, rel, full):
        if rel in self.read_files or not os.path.isfile(full):
            return
        self.read_files.add(rel)
        for line in read(full).splitlines():
            line = line.split(" #")[0].strip()
            if re.match(r"^(-r|-c|--requirement|--constraint)\s*", line):
                target = re.sub(r"^(-r|-c|--requirement|--constraint)\s*=?\s*", "", line)
                base = os.path.dirname(rel)
                self.requirements(os.path.normpath(os.path.join(base, target)), os.path.join(self.root, base, target))
            elif re.match(r"^(-i|--index-url|--extra-index-url)\b", line):
                self.private = True
            else:
                self.add_spec(line, rel)

    def setup_cfg(self, rel, full):
        parser = configparser.ConfigParser(interpolation=None)
        try:
            parser.read_string(read(full))
        except configparser.Error:
            self.unknown.append(rel + ": not INI")
            return
        if parser.has_option("options", "install_requires"):
            for line in parser.get("options", "install_requires").splitlines():
                self.add_spec(line, rel)
        if parser.has_section("options.extras_require"):
            for _, value in parser.items("options.extras_require"):
                for line in value.splitlines():
                    self.add_spec(line, rel)

    def setup_py(self, rel, full):
        try:
            tree = ast.parse(read(full))
        except SyntaxError:
            self.unknown.append(rel + ": not Python")
            return
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            for keyword in node.keywords:
                if keyword.arg not in ("install_requires", "extras_require", "tests_require"):
                    continue
                lists = [keyword.value]
                if keyword.arg == "extras_require":
                    lists = keyword.value.values if isinstance(keyword.value, ast.Dict) else [None]
                for value in lists:
                    if isinstance(value, (ast.List, ast.Tuple)) and all(
                            isinstance(e, ast.Constant) and isinstance(e.value, str) for e in value.elts):
                        for element in value.elts:
                            self.add_spec(element.value, rel)
                    else:
                        self.unknown.append(rel + ": " + keyword.arg + " is not a literal list")

    def pipfile(self, rel, full):
        try:
            data = tomllib.loads(read(full))
        except tomllib.TOMLDecodeError:
            self.unknown.append(rel + ": not TOML")
            return
        for table in ("packages", "dev-packages"):
            for name, value in (data.get(table, {}) or {}).items():
                registry = not (isinstance(value, dict) and ("path" in value or "git" in value))
                self.add(name, rel, registry)

    def declares(self, module, variant):
        key = norm(module)
        if key in self.dists:
            return True
        if variant in ("table", "prefix") and any(d in self.dists for d in TABLE.get(module, ())):
            return True
        if variant == "prefix" and any(d.startswith(key + "-") for d in self.dists):
            return True
        return False


