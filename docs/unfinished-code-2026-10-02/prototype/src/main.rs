#[derive(Clone, Copy, PartialEq)]
enum Lang {
    Rust,
    Python,
    Ts,
}

struct Site {
    candidate: &'static str,
    shape: String,
    file: String,
    line: usize,
    exclusions: Vec<&'static str>,
    text: String,
    name: Option<String>,
}

struct File<'a> {
    lang: Lang,
    path: &'a str,
    src: &'a [u8],
    lines: Vec<&'a str>,
    test: bool,
    generated: bool,
    example: bool,
    stub_file: bool,
    test_ranges: Vec<(usize, usize)>,
}

